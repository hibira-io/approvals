export const locales = { en, 'zh-TW': zhTW, 'zh-CN': zhCN, ja, ko, th, vi };

/** Labels for `locale` (falls back on the language, then English) with `overrides` on top. */
export function labelsFor(locale, overrides) {
  const exact = locale && locales[locale];
  const lang = locale && !exact ? locales[locale.split('-')[0]] ?? (locale.startsWith('zh') ? zhTW : null) : null;
  const picked = exact ?? lang ?? en;
  return {
    ...en,
    ...picked,
    ...(overrides ?? {}),
    status: { ...en.status, ...picked.status, ...(overrides?.status ?? {}) },
    decision: { ...en.decision, ...picked.decision, ...(overrides?.decision ?? {}) },
  };
}

export function format(text, values) {
  return text.replace(/\{(\w+)\}/g, (_, k) => (values[k] ?? `{${k}}`));
}
